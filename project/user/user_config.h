/*
 * 快速上手步骤：
 *
 * 第一步：选择陀螺仪
 *   - 根据实际使用的陀螺仪型号，取消注释对应的宏定义
 *   - 确认硬件接线正确
 *
 * 第二步：基础测试
 *   - 编译下载程序
 *   - 测试角度闭环是否正常（用手转动车身，观察是否回正）
 *   - 测试车轮转向是否正确
 *
 * 第三步：参数调整
 *   - 根据实际响应调整PID参数
 *   - 根据测试结果调整速度限制
 *
 * 第四步：功能测试
 *   - 测试全向移动
 *   - 测试全局定位
 *   - 测试定点导航
 *
 * 第五步：校准参数
 *   - 移动已知距离，调整ODOMETRY_QUICK_SCALE
 *   - 测试多点路径，验证精度
 *
 * 常见配置场景：
 *
 * 场景1：仅测试角度闭环
 *   - 开启：MODE_ANGLE_CONTROL
 *   - 关闭：MODE_OMNI_MOVEMENT, MODE_GLOBAL_CONTROL
 *   - 运行：example_angle_control_test()
 *
 * 场景2：测试全向移动
 *   - 开启：MODE_ANGLE_CONTROL, MODE_OMNI_MOVEMENT
 *   - 关闭：MODE_GLOBAL_CONTROL
 *   - 运行：example_omni_movement_test()
 *
 * 场景3：测试全局定位
 *   - 开启：MODE_ANGLE_CONTROL, MODE_OMNI_MOVEMENT, MODE_GLOBAL_CONTROL
 *   - 运行：example_move_to_position()
 *
 * 参数调整建议：
 *
 * 角度PID调整顺序：
 *   1. 先调整Kp：从1.0开始，逐步增加，观察响应速度
 *   2. 再调整Kd：出现超调时增加，消除震荡
 *   3. 最后调整Ki：有静差时增加，但要防止积分饱和
 *
 * 车轮PID调整顺序：
 *   1. 先调整Kp：从0.5开始，逐步增加，观察转速响应
 *   2. 再调整Ki：有稳态误差时增加
 *   3. Kd一般不需要设置
 *
 * 速度限制建议：
 *   - 初期调试：使用较低速度（30-50 cm/s）
 *   - 确认稳定后：逐步提高速度
 *   - 最大速度：不超过电机额定值
 */

